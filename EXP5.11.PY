# Tuple creation
tup = (1, 2, 3, 4, 5)

# Accessing elements
print("First element:", tup[0])
print("Last element:", tup[-1])

# Slicing
print("Slice (2nd to 4th element):", tup[1:4])

# Tuple concatenation
tup2 = (6, 7, 8)
print("Concatenated Tuple:", tup + tup2)

# Repetition
print("Repeated Tuple:", tup * 2)

# Membership check
print("Is 3 in tuple?", 3 in tup)

# Tuple length
print("Tuple length:", len(tup))
